from enum import StrEnum

from pydantic import BaseModel, Field

from sibyl.config import MAX_SCORE


class Recommendation(StrEnum):
    """Enumeration of possible review recommendations."""

    ACCEPT = "Accept"
    MINOR_REVISION = "Minor Revision"
    MAJOR_REVISION = "Major Revision"
    REJECT = "Reject"


class LLMReply(BaseModel):
    """Structured reply from an LLM for a paper review.

    Default reviews fill the narrative sections (novelty ... detailed_feedback). Form reviews (custom or
    conference) fill only ``review_form_response`` plus ``score`` and ``recommendation``, so the narrative
    sections stay empty.
    """

    novelty: str = Field(default="", description="Assessment of novelty and originality")
    methodology: str = Field(default="", description="Evaluation of methodology and experimental design")
    results: str = Field(default="", description="Analysis of results and their significance")
    clarity: str = Field(default="", description="Assessment of writing quality, clarity and presentation")
    impact: str = Field(default="", description="Evaluation of potential impact and contribution to the field")
    limitations: str = Field(default="", description="Identified limitations and weaknesses")
    strengths: str = Field(default="", description="Key strengths")
    score: int = Field(..., ge=1, le=MAX_SCORE, description=f"Overall score from 1-{MAX_SCORE}")
    recommendation: Recommendation = Field(..., description="Accept/Minor Revision/Major Revision/Reject")
    detailed_feedback: str = Field(default="", description="Detailed feedback and suggestions for improvement")
    review_form_response: str | None = Field(
        default=None,
        description="Completed response matching the user-supplied review form, or null when no form was supplied",
    )
    # Filled in by Sibyl (never generated by the model) when a conference template is used.
    conference: str | None = Field(default=None, description="Conference template id used for this review")
    review_form_answers: dict[str, int | str] | None = Field(default=None, description="Per-question answers to the conference form")


NARRATIVE_FIELDS = ("novelty", "methodology", "results", "clarity", "impact", "limitations", "strengths", "detailed_feedback")
"""Sibyl's default review sections, generated only when no review form is selected."""

SIBYL_FILLED_FIELDS = ("conference", "review_form_answers")
"""LLMReply fields populated by Sibyl after generation; they are removed from the schema sent to the model."""


class FormAwareLLMReply(LLMReply):
    """Structured reply used when a custom review form must be completed."""

    review_form_response: str = Field(
        ...,
        min_length=1,
        description="Completed response matching every applicable section of the user-supplied review form",
    )
